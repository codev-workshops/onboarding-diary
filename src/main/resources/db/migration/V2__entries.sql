CREATE TABLE task_entries (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id    BIGINT        NOT NULL,
  entry_date  DATE          NOT NULL,
  title       VARCHAR(120)  NOT NULL,
  description VARCHAR(4000),
  category    VARCHAR(20)   NOT NULL,
  status      VARCHAR(20)   NOT NULL,
  priority    VARCHAR(10)   NOT NULL,
  created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
  updated_at  TIMESTAMP WITH TIME ZONE NOT NULL,
  CONSTRAINT fk_task_owner FOREIGN KEY (owner_id) REFERENCES users (id)
);
CREATE INDEX ix_task_owner_date ON task_entries (owner_id, entry_date);

CREATE TABLE issue_entries (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id         BIGINT        NOT NULL,
  entry_date       DATE          NOT NULL,
  title            VARCHAR(120)  NOT NULL,
  description      VARCHAR(4000),
  severity         VARCHAR(10)   NOT NULL,
  status           VARCHAR(20)   NOT NULL,
  resolution_notes VARCHAR(4000),
  resolved_at      TIMESTAMP WITH TIME ZONE,
  created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
  updated_at       TIMESTAMP WITH TIME ZONE NOT NULL,
  CONSTRAINT fk_issue_owner FOREIGN KEY (owner_id) REFERENCES users (id)
);
CREATE INDEX ix_issue_owner_date ON issue_entries (owner_id, entry_date);

CREATE TABLE feedback_entries (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id   BIGINT        NOT NULL,
  entry_date DATE          NOT NULL,
  subject    VARCHAR(120)  NOT NULL,
  type       VARCHAR(20)   NOT NULL,
  details    VARCHAR(4000) NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
  CONSTRAINT fk_feedback_owner FOREIGN KEY (owner_id) REFERENCES users (id)
);
CREATE INDEX ix_feedback_owner_date ON feedback_entries (owner_id, entry_date);

CREATE TABLE notes (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id   BIGINT         NOT NULL,
  entry_date DATE           NOT NULL,
  title      VARCHAR(120)   NOT NULL,
  content    VARCHAR(10000) NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
  CONSTRAINT fk_note_owner FOREIGN KEY (owner_id) REFERENCES users (id)
);
CREATE INDEX ix_note_owner_date ON notes (owner_id, entry_date);

CREATE TABLE note_tags (
  note_id BIGINT      NOT NULL,
  tag     VARCHAR(30) NOT NULL,
  CONSTRAINT pk_note_tags PRIMARY KEY (note_id, tag),
  CONSTRAINT fk_note_tags_note FOREIGN KEY (note_id) REFERENCES notes (id) ON DELETE CASCADE
);
CREATE INDEX ix_note_tags_tag ON note_tags (tag);
