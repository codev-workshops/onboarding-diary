CREATE TABLE checklist_templates (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  created_by BIGINT NOT NULL REFERENCES users (id),
  created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE checklist_template_items (
  template_id BIGINT NOT NULL REFERENCES checklist_templates (id) ON DELETE CASCADE,
  item_order INT NOT NULL,
  label VARCHAR(200) NOT NULL,
  PRIMARY KEY (template_id, item_order)
);

CREATE TABLE recruit_checklists (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  recruit_id BIGINT NOT NULL REFERENCES users (id),
  name VARCHAR(100) NOT NULL,
  assigned_by BIGINT NOT NULL REFERENCES users (id),
  assigned_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_recruit_checklists_recruit ON recruit_checklists (recruit_id);

CREATE TABLE recruit_checklist_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  checklist_id BIGINT NOT NULL REFERENCES recruit_checklists (id) ON DELETE CASCADE,
  item_order INT NOT NULL,
  label VARCHAR(200) NOT NULL,
  done BOOLEAN NOT NULL DEFAULT FALSE,
  done_at TIMESTAMP WITH TIME ZONE
);
